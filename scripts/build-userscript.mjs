import { readFile, mkdir } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { build, context } from "esbuild";

const root = path.resolve(import.meta.dirname, "..");
const metadataTemplate = (await readFile(
  path.join(root, "userscript.meta.js"),
  "utf8",
)).trimEnd();
const packageJson = JSON.parse(
  await readFile(path.join(root, "package.json"), "utf8"),
);
if (!metadataTemplate.includes("// @version      __VERSION__")) {
  throw new Error("userscript.meta.js must contain the __VERSION__ placeholder");
}
const metadata = `${metadataTemplate.replaceAll("__VERSION__", packageJson.version)}\n\n// Generated from src/ by npm run build. Do not edit this file directly.`;

const outputDirectory = path.join(root, "dist");
await mkdir(outputDirectory, { recursive: true });

const options = {
  entryPoints: [path.join(root, "src", "main.js")],
  outfile: path.join(
    outputDirectory,
    `3place-pathfinder-v${packageJson.version}.user.js`,
  ),
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["chrome120", "firefox121", "safari17"],
  legalComments: "none",
  charset: "utf8",
  sourcemap: false,
  define: {
    __PATHFINDER_VERSION__: JSON.stringify(packageJson.version),
  },
  banner: { js: metadata },
  logLevel: "info",
};

if (process.argv.includes("--watch")) {
  const buildContext = await context(options);
  await buildContext.watch();
  console.log("Watching userscript sources. Press Ctrl+C to stop.");
} else {
  await build(options);
}
